<script>
    const canvas = document.getElementById('animation-bg');
const ctx = canvas.getContext('2d');

// Set canvas size to match header container
function resizeCanvas() {
    canvas.width = canvas.parentElement.offsetWidth;
    canvas.height = canvas.parentElement.offsetHeight;
}
resizeCanvas();
window.addEventListener('resize', resizeCanvas);

const particlesArray = [];
const numberOfParticles = 80; // Adjust density

// Track mouse position
const mouse = {
    x: null,
    y: null,
    radius: 150 // How far the mouse effect reaches
};

// Listen for mouse movement over the header container parent
canvas.parentElement.addEventListener('mousemove', (event) => {
    const rect = canvas.getBoundingClientRect();
    mouse.x = event.clientX - rect.left;
    mouse.y = event.clientY - rect.top;
});

// Clear mouse position when it leaves the header
canvas.parentElement.addEventListener('mouseleave', () => {
    mouse.x = null;
    mouse.y = null;
});

// Particle blueprint
class Particle {
    constructor() {
        this.x = Math.random() * canvas.width;
        this.y = Math.random() * canvas.height;
        this.size = Math.random() * 3 + 1; // Particle thickness
        this.speedX = (Math.random() - 0.5) * 1; // Subtle movement speed
        this.speedY = (Math.random() - 0.5) * 1;
        this.baseX = this.x;
        this.baseY = this.y;
    }

    update() {
        // Natural movement
        this.x += this.speedX;
        this.y += this.speedY;

        // Bounce off canvas walls
        if (this.x < 0 || this.x > canvas.width) this.speedX = -this.speedX;
        if (this.y < 0 || this.y > canvas.height) this.speedY = -this.speedY;

        // Interactive mouse interaction (Slight magnet/push effect)
        if (mouse.x !== null && mouse.y !== null) {
            let dx = mouse.x - this.x;
            let dy = mouse.y - this.y;
            let distance = Math.sqrt(dx * dx + dy * dy);

            if (distance < mouse.radius) {
                // Gentle pull towards mouse (change signs to '-' to push away)
                this.x += dx * 0.02;
                this.y += dy * 0.02;
            }
        }
    }

    draw() {
        ctx.fillStyle = 'rgba(212, 175, 55, 0.7)'; // Warm elegant gold particles
        ctx.beginPath();
        ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
        ctx.fill();
    }
}

// Initialize particles
function init() {
    for (let i = 0; i < numberOfParticles; i++) {
        particlesArray.push(new Particle());
    }
}

// Connect nearby dots with lines
function drawLines() {
    for (let a = 0; a < particlesArray.length; a++) {
        for (let b = a; b < particlesArray.length; b++) {
            let dx = particlesArray[a].x - particlesArray[b].x;
            let dy = particlesArray[a].y - particlesArray[b].y;
            let distance = Math.sqrt(dx * dx + dy * dy);

            if (distance < 120) { // Max distance to draw a line
                // The closer they are, the more opaque the line
                let opacity = 1 - (distance / 120);
                ctx.strokeStyle = `rgba(255, 255, 255, ${opacity * 0.15})`;
                ctx.lineWidth = 1;
                ctx.beginPath();
                ctx.moveTo(particlesArray[a].x, particlesArray[a].y);
                ctx.lineTo(particlesArray[b].x, particlesArray[b].y);
                ctx.stroke();
            }
        }
    }
}

// Animation Loop
function animate() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    for (let i = 0; i < particlesArray.length; i++) {
        particlesArray[i].update();
        particlesArray[i].draw();
    }

    drawLines();
    requestAnimationFrame(animate);
}

init();
animate();
</script>
